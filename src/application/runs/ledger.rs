//! Every run in creation order, with a constant-time lookup by id.
//!
//! The index cannot go stale by construction: a run's id is private to
//! `application::runs` (no `&mut Run` can change it), and the order changes
//! only through the methods here (`push`, `pop`, `truncate`, `extend`,
//! replacing the whole ledger), each of which keeps the index in step. There
//! is no `DerefMut` to a slice, so nothing can sort, swap or reverse runs in
//! place. Lookups still confirm the id at the indexed position (a mismatch
//! falls back to a scan), and debug builds assert that a miss is a real miss:
//! that catches a run replaced wholesale through `&mut Run`, which no code does.
use super::Run;
use std::collections::HashMap;

/// Runs past the indexed prefix are found by scanning, at most this many.
/// Most rollbacks pop or truncate runs pushed moments earlier, so they never
/// touch the map; a longer tail is indexed on the next push.
const TAIL: usize = 8;

#[derive(Default)]
pub(crate) struct Runs {
    list: Vec<Run>,
    /// `list[..indexed]` is in `index`; the rest is the scanned tail.
    indexed: usize,
    /// The first position in the indexed prefix of each id's hash. First-wins
    /// keeps the linear `find` this replaced (ids are unique anyway). Keys are
    /// hashes, not ids, so indexing copies no string. Every hit is checked
    /// against the id at that position; a hash shared by two ids falls back
    /// to a full scan, so collisions cost time, never answers.
    index: HashMap<u64, usize, std::hash::BuildHasherDefault<Hashed>>,
}
/// Run ids are generated by Control (creation stamp and sequence), so the
/// index needs no HashDoS-resistant SipHash: it hashes each id once, eight
/// bytes at a time (the FxHash step), and the map uses that value as is. An id
/// chosen by a caller only looks a run up; a crafted collision makes that
/// lookup a linear scan, the cost every lookup had before the index.
fn key(id: &str) -> u64 {
    let hash = id.as_bytes().chunks(8).fold(id.len() as u64, |hash, chunk| {
        let mut word = [0; 8];
        word[..chunk.len()].copy_from_slice(chunk);
        (hash.rotate_left(5) ^ u64::from_le_bytes(word)).wrapping_mul(0x517c_c1b7_2722_0a95)
    });
    hash ^ (hash >> 32)
}
#[derive(Default)]
pub(crate) struct Hashed(u64);
impl std::hash::Hasher for Hashed {
    fn finish(&self) -> u64 {
        self.0
    }
    fn write(&mut self, _: &[u8]) {
        unreachable!("the run index hashes only u64 keys")
    }
    fn write_u64(&mut self, hash: u64) {
        self.0 = hash;
    }
}
impl Runs {
    fn indexed(list: Vec<Run>) -> Self {
        let mut runs = Self {
            index: HashMap::with_capacity_and_hasher(list.len(), Default::default()),
            list,
            indexed: 0,
        };
        runs.index_tail();
        runs
    }
    fn index_tail(&mut self) {
        for (position, run) in self.list.iter().enumerate().skip(self.indexed) {
            self.index.entry(key(run.id())).or_insert(position);
        }
        self.indexed = self.list.len();
    }
    /// Forgets the indexed runs from `len` on.
    fn unindex_from(&mut self, len: usize) {
        for (position, run) in self.list.iter().enumerate().take(self.indexed).skip(len) {
            let hash = key(run.id());
            if self.index.get(&hash) == Some(&position) {
                self.index.remove(&hash);
            }
        }
        self.indexed = self.indexed.min(len);
    }
    /// The run with this id.
    pub(crate) fn get(&self, id: &str) -> Option<&Run> {
        self.position(id).map(|position| &self.list[position])
    }
    pub(crate) fn get_mut(&mut self, id: &str) -> Option<&mut Run> {
        self.position(id).map(|position| &mut self.list[position])
    }
    /// Where the run with this id sits, for edits that hold a position.
    pub(crate) fn position(&self, id: &str) -> Option<usize> {
        let found = match self.index.get(&key(id)) {
            Some(&position) if self.list[position].id() == id => Some(position),
            Some(_) => self.list.iter().position(|run| run.id() == id),
            None => self.list[self.indexed..]
                .iter()
                .position(|run| run.id() == id)
                .map(|offset| self.indexed + offset),
        };
        debug_assert!(
            found.is_some() || self.list.iter().all(|run| run.id() != id),
            "run index is stale for {id}"
        );
        found
    }
    pub(crate) fn push(&mut self, run: Run) {
        self.list.push(run);
        if self.list.len() - self.indexed > TAIL {
            self.index_tail();
        }
    }
    pub(crate) fn pop(&mut self) -> Option<Run> {
        self.unindex_from(self.list.len().checked_sub(1)?);
        self.list.pop()
    }
    /// Drops runs added after the first `len` (rolling back an unsaved edit).
    pub(crate) fn truncate(&mut self, len: usize) {
        self.unindex_from(len);
        self.list.truncate(len);
    }
    pub(crate) fn iter_mut(&mut self) -> std::slice::IterMut<'_, Run> {
        self.list.iter_mut()
    }
    pub(crate) fn last_mut(&mut self) -> Option<&mut Run> {
        self.list.last_mut()
    }
    /// Test fixtures reshape runs freely (remove, rename, reorder); the index
    /// is rebuilt afterwards.
    #[cfg(test)]
    pub(crate) fn rebuild(&mut self, edit: impl FnOnce(&mut Vec<Run>)) {
        let mut list = std::mem::take(&mut self.list);
        edit(&mut list);
        *self = Self::indexed(list);
    }
    /// The runs in creation order, leaving this ledger empty.
    pub(crate) fn into_vec(self) -> Vec<Run> {
        self.list
    }
}
impl std::ops::Deref for Runs {
    type Target = [Run];
    fn deref(&self) -> &[Run] {
        &self.list
    }
}
// Positions and ranges read like a slice; only single runs can be edited in place.
// Positions and ranges read like a slice; only single runs are edited in place.
impl<I: std::slice::SliceIndex<[Run]>> std::ops::Index<I> for Runs {
    type Output = I::Output;
    fn index(&self, position: I) -> &I::Output {
        &self.list[position]
    }
}
impl std::ops::IndexMut<usize> for Runs {
    fn index_mut(&mut self, position: usize) -> &mut Run {
        &mut self.list[position]
    }
}
impl From<Vec<Run>> for Runs {
    fn from(list: Vec<Run>) -> Self {
        Self::indexed(list)
    }
}
impl FromIterator<Run> for Runs {
    fn from_iter<I: IntoIterator<Item = Run>>(runs: I) -> Self {
        Self::indexed(runs.into_iter().collect())
    }
}
impl Extend<Run> for Runs {
    fn extend<I: IntoIterator<Item = Run>>(&mut self, runs: I) {
        runs.into_iter().for_each(|run| self.push(run));
    }
}
/// Saved as the plain array it always was; the index is rebuilt on load.
impl<'de> serde::Deserialize<'de> for Runs {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Vec::<Run>::deserialize(deserializer).map(Self::indexed)
    }
}
impl serde::Serialize for Runs {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        self.list.serialize(serializer)
    }
}

